@dataclass(frozen=True)
class DatabaseCompatibility:
    compatible: bool
    status: str
    current_revision: str | None = None
    missing_table: str | None = None
    missing_columns: tuple[str, ...] = ()


def check_database_compatibility(engine: Engine) -> DatabaseCompatibility:
    try:
        with engine.connect() as connection:
            inspector = inspect(connection)
            if "alembic_version" not in inspector.get_table_names():
                return DatabaseCompatibility(False, "MIGRATION_HISTORY_MISSING")
            revision = connection.scalar(text("SELECT version_num FROM alembic_version"))
            if revision != EXPECTED_DATABASE_REVISION:
                return DatabaseCompatibility(False, "MIGRATION_REQUIRED", str(revision or ""))
            tables = set(inspector.get_table_names())
            for table_name, required in REQUIRED_COLUMNS.items():
                if table_name not in tables:
                    return DatabaseCompatibility(
                        False,
                        "SCHEMA_INCOMPLETE",
                        str(revision),
                        missing_table=table_name,
                    )
                actual = {column["name"] for column in inspector.get_columns(table_name)}
                if not required <= actual:
                    return DatabaseCompatibility(
                        False,
                        "SCHEMA_INCOMPLETE",
                        str(revision),
                        missing_table=table_name,
                        missing_columns=tuple(sorted(required - actual)),
                    )
            return DatabaseCompatibility(True, "READY", str(revision))
    except SQLAlchemyError:
        return DatabaseCompatibility(False, "DATABASE_UNREACHABLE")

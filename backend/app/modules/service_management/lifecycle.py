REASON_REQUIRED = {"CANCELLED", "REJECTED", "FAILED", "ROLLED_BACK"}


def validate_transition(matrix: dict[str, set[str]], current: str, target: str, reason: str | None = None) -> None:
    if target not in matrix.get(current, set()):
        raise ConflictError("INVALID_LIFECYCLE_TRANSITION", f"Cannot transition from {current} to {target}.")
    if (target in REASON_REQUIRED or current in {"CLOSED", "CANCELLED", "REJECTED", "FAILED", "ROLLED_BACK"}) and not (reason or "").strip():
        raise ConflictError("TRANSITION_REASON_REQUIRED", "A documented reason is required for this transition.")
